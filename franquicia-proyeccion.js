const ids=['area','sqmPerLine','lines','hours','washesPerLineDay','days','ticket','consumables','paymentFee','novaFee','staffPerLine','cashiers','staffCost','rent','utilities','setup'];
const el=Object.fromEntries(ids.map(id=>[id,document.getElementById(id)]));
const out=id=>document.getElementById(id);
const cop=new Intl.NumberFormat('es-CO',{style:'currency',currency:'COP',maximumFractionDigits:0});
const number=id=>Math.max(0,Number(el[id].value)||0);
const textMoney=value=>cop.format(Math.round(value));

function calculate(){
  const area=number('area'), sqmPerLine=Math.max(1,number('sqmPerLine'));
  const recommendedLines=Math.max(1,Math.floor(area/sqmPerLine));
  el.lines.max=recommendedLines;
  if(number('lines')>recommendedLines) el.lines.value=recommendedLines;
  const lines=Math.max(1,number('lines'));
  const hours=number('hours'), days=number('days');
  const maxDailyPerLine=Math.max(1,Math.floor(hours*60/25*3));
  el.washesPerLineDay.max=maxDailyPerLine;
  if(number('washesPerLineDay')>maxDailyPerLine) el.washesPerLineDay.value=maxDailyPerLine;
  const dailyPerLine=number('washesPerLineDay');
  const monthlyWashes=dailyPerLine*lines*days;
  const monthlyCapacity=maxDailyPerLine*lines*days;
  const revenue=monthlyWashes*number('ticket');
  const consumables=monthlyWashes*number('consumables');
  const fees=revenue*((number('paymentFee')+number('novaFee'))/100);
  const payroll=(lines*number('staffPerLine')+number('cashiers'))*number('staffCost');
  const fixed=number('rent')+number('utilities');
  const profit=revenue-consumables-fees-payroll-fixed;
  const annualProfit=profit*12, setup=number('setup');
  const roi=setup>0?annualProfit/setup*100:null;
  const usage=monthlyCapacity?monthlyWashes/monthlyCapacity*100:0;
  out('lineHint').textContent=`máx. ${recommendedLines}`;
  out('capacityHint').textContent=`cap. máx. ${maxDailyPerLine}`;
  out('monthlyProfit').textContent=textMoney(profit);
  out('monthlyMargin').textContent=`${revenue?Math.round(profit/revenue*100):0}% margen operativo estimado`;
  out('monthlyWashes').textContent=new Intl.NumberFormat('es-CO').format(monthlyWashes);
  out('monthlyRevenue').textContent=textMoney(revenue);
  out('annualProfit').textContent=textMoney(annualProfit);
  out('annualRoi').textContent=roi===null?'—':`${Math.round(roi)}%`;
  out('capacityUsage').textContent=`${Math.round(usage)}%`;
  out('capacityBar').style.width=`${Math.min(100,usage)}%`;
  out('capacityCopy').textContent=`${new Intl.NumberFormat('es-CO').format(monthlyCapacity)} lavadas/mes de capacidad técnica. Meta comercial de referencia: 500 vehículos/mes.`;
  out('rowRevenue').textContent=textMoney(revenue);
  out('rowConsumables').textContent=`− ${textMoney(consumables)}`;
  out('rowFees').textContent=`− ${textMoney(fees)}`;
  out('rowPayroll').textContent=`− ${textMoney(payroll)}`;
  out('rowFixed').textContent=`− ${textMoney(fixed)}`;
}
ids.forEach(id=>el[id].addEventListener('input',calculate));
document.getElementById('franchiseCalculator').addEventListener('submit',event=>event.preventDefault());
calculate();
